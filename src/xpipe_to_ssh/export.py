"""Bulk export of every XPipe SSH connection to a portable document.

The single-connection path emits one ``ssh`` argv. This module reduces the same
validated argv into the fields an OpenSSH client config, a hosts YAML document,
or an Ansible inventory needs. Parsing the argv produced by ``build_ssh_argv``
- rather than re-reading the XPipe record - keeps command validation and field
extraction on a single code path, so an exported file can never disagree with
the command the CLI would run.
"""

from __future__ import annotations

import contextlib
import json
import os
import re
import shlex
import tempfile
from dataclasses import dataclass, field, replace
from pathlib import Path
from typing import Any, Literal

import yaml

from . import __version__
from .errors import ExportError, ExportOutputError, InternalError
from .models import SSHCommand
from .ssh import build_ssh_argv
from .xpipe import WireRecord, connection_type, display_path, store_id

ExportFormat = Literal["ssh-config", "yaml", "json", "ansible"]
#: Shared with the argument parser so the two cannot drift.
EXPORT_CHOICES: tuple[ExportFormat, ...] = ("ssh-config", "yaml", "json", "ansible")
#: ``--output -`` keeps the document on stdout.
STDOUT_TARGET = "-"

EXPORT_HEADER = f"# Generated by xpipe-to-ssh {__version__} from XPipe. Do not edit by hand."

#: A stored name becomes an SSH config ``Host`` pattern and an Ansible host
#: name, where whitespace and glob characters would change the meaning of the
#: line. Everything outside this set is folded to ``-``.
_SAFE_NAME = re.compile(r"[^A-Za-z0-9._/@-]+")
_SAFE_INVENTORY_NAME = re.compile(r"[^A-Za-z0-9._@-]+")
#: An ssh option is written ``Key=Value`` or ``Key Value``; both appear in
#: XPipe's additionalOptions.
_OPTION_SEPARATOR = re.compile(r"[=\s]+")
#: argv flags that consume the next token.
_VALUE_FLAGS = frozenset({"-p", "-l", "-i", "-o"})
#: additionalOptions that change where an ssh config block ends rather than
#: setting a value. Writing one inside a generated ``Host`` block would attach
#: the following directives to the wrong host, so they are dropped explicitly.
_BLOCK_OPTIONS = frozenset({"host", "match", "include"})


@dataclass(frozen=True)
class CommandFields:
    """The parts of a generated ssh command that a config file can express."""

    hostname: str
    username: str | None
    port: int | None
    identity_files: list[str]
    forward_x11: bool
    proxy_command: str | None
    options: list[tuple[str, str]]


@dataclass
class ExportHost:
    """One connection, ready to be serialized by any format."""

    name: str
    alias: str
    id: str
    type: str
    fields: CommandFields
    available_hosts: list[str]
    auth_methods: list[str]
    gateways: list[str]


@dataclass
class ExportResult:
    """The collected export plus everything worth telling the user about it."""

    hosts: list[ExportHost] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def sanitize_alias(name: str, *, allow_slash: bool = True) -> str:
    """Fold a stored name into a safe SSH config alias or inventory name."""
    pattern = _SAFE_NAME if allow_slash else _SAFE_INVENTORY_NAME
    cleaned = pattern.sub("-", name).strip("-./")
    return cleaned or "xpipe"


def unique_names(names: list[str]) -> list[str]:
    """Disambiguate duplicates in order, so output stays deterministic."""
    seen: dict[str, int] = {}
    result: list[str] = []
    for name in names:
        seen[name] = seen.get(name, 0) + 1
        count = seen[name]
        result.append(name if count == 1 else f"{name}-{count}")
    return result


def _split_option(value: str) -> tuple[str, str]:
    parts = _OPTION_SEPARATOR.split(value, maxsplit=1)
    if len(parts) != 2 or not parts[0]:
        raise InternalError(f"Unsupported ssh option in export: {value!r}")
    return parts[0], parts[1]


def command_fields(command: SSHCommand) -> CommandFields:
    """Read the SSH-relevant fields back out of a generated argv."""
    argv = command.argv
    if not argv or argv[0] != "ssh" or len(argv) < 2:
        raise InternalError(f"Cannot export an unexpected ssh argv: {argv!r}")
    hostname = argv[-1]
    username: str | None = None
    port: int | None = None
    identity_files: list[str] = []
    forward_x11 = False
    proxy_command: str | None = None
    options: list[tuple[str, str]] = []

    index = 1
    while index < len(argv) - 1:
        token = argv[index]
        if token == "-X":
            forward_x11 = True
            index += 1
        elif token in _VALUE_FLAGS:
            value = argv[index + 1]
            if token == "-p":
                port = int(value)
            elif token == "-l":
                username = value
            elif token == "-i":
                identity_files.append(value)
            else:
                key, directive_value = _split_option(value)
                if key.casefold() == "proxycommand":
                    proxy_command = directive_value
                else:
                    options.append((key, directive_value))
            index += 2
        else:
            # build_ssh_argv is the only producer; an unknown token means the
            # planner grew an argument the exporter does not understand yet.
            raise InternalError(f"Unsupported ssh argument in export: {token!r}")

    return CommandFields(
        hostname=hostname,
        username=username,
        port=port,
        identity_files=identity_files,
        forward_x11=forward_x11,
        proxy_command=proxy_command,
        options=options,
    )


def build_export_host(command: SSHCommand, warnings: list[str]) -> ExportHost:
    fields = command_fields(command)
    dropped = [key for key, _ in fields.options if key.casefold() in _BLOCK_OPTIONS]
    if dropped:
        warnings.append(
            f"{command.connection_name}: ignored additional option(s) that would split a "
            f"config block: {', '.join(dropped)}"
        )
        fields = replace(
            fields,
            options=[
                (key, value)
                for key, value in fields.options
                if key.casefold() not in _BLOCK_OPTIONS
            ],
        )
    return ExportHost(
        name=command.connection_name,
        alias=sanitize_alias(command.connection_name),
        id=command.connection_id,
        type=command.connection_type,
        fields=fields,
        available_hosts=list(command.available_hosts),
        auth_methods=list(command.auth_methods),
        gateways=list(command.gateway_names),
    )


def collect_export(client: object, infos: list[WireRecord]) -> ExportResult:
    """Reduce every exportable store to an ``ExportHost``.

    One unreadable connection must not sink a whole export, so a failure is
    recorded as a warning and the connection is skipped; ``--strict`` turns
    those warnings back into a hard failure for automation.
    """
    result = ExportResult()
    for info in sorted(infos, key=lambda item: display_path(item).casefold()):
        name = display_path(info) or store_id(info) or "<unnamed>"
        if connection_type(info) == "sshConfigHost":
            # Its directives already live in the user's ~/.ssh/config; copying
            # the alias into a generated file would only shadow that entry.
            result.warnings.append(
                f"Skipped {name!r}: an ssh config host already resolves through ~/.ssh/config."
            )
            continue
        try:
            command = build_ssh_argv(client, info)
        except ExportError as exc:
            result.warnings.append(f"Skipped {name!r}: {exc}")
            continue
        result.warnings.extend(f"{name}: {warning}" for warning in command.warnings)
        result.hosts.append(build_export_host(command, result.warnings))

    for host, alias in zip(
        result.hosts, unique_names([host.alias for host in result.hosts]), strict=True
    ):
        host.alias = alias
    return result


def _ssh_config_directives(host: ExportHost) -> list[tuple[str, str]]:
    fields = host.fields
    directives: list[tuple[str, str]] = [("HostName", fields.hostname)]
    if fields.username:
        directives.append(("User", fields.username))
    if fields.port is not None:
        directives.append(("Port", str(fields.port)))
    directives.extend(("IdentityFile", path) for path in fields.identity_files)
    if fields.forward_x11:
        directives.append(("ForwardX11", "yes"))
    if fields.proxy_command:
        directives.append(("ProxyCommand", fields.proxy_command))
    directives.extend(fields.options)
    return directives


def render_ssh_config(hosts: list[ExportHost]) -> str:
    lines = [
        EXPORT_HEADER,
        "# Include this file from ~/.ssh/config, for example:",
        "#   Include ~/.ssh/config.d/xpipe.conf",
    ]
    for host in hosts:
        lines.append("")
        lines.append(f"# XPipe connection: {host.name}")
        lines.append(f"Host {host.alias}")
        lines.extend(f"    {key} {value}" for key, value in _ssh_config_directives(host))
    return "\n".join(lines) + "\n"


def _host_record(host: ExportHost) -> dict[str, Any]:
    fields = host.fields
    record: dict[str, Any] = {
        "name": host.name,
        "alias": host.alias,
        "id": host.id,
        "type": host.type,
        "hostname": fields.hostname,
    }
    if fields.username:
        record["user"] = fields.username
    if fields.port is not None:
        record["port"] = fields.port
    if fields.identity_files:
        record["identityFiles"] = list(fields.identity_files)
    if fields.forward_x11:
        record["forwardX11"] = True
    if fields.proxy_command:
        record["proxyCommand"] = fields.proxy_command
    if fields.options:
        # XPipe's additionalOptions is a key/value list; a mapping keeps the
        # common, duplicate-free case readable. ssh-config output is lossless
        # for the rare duplicate.
        record["options"] = {key: value for key, value in fields.options}
    if len(host.available_hosts) > 1:
        record["availableHosts"] = list(host.available_hosts)
    if host.auth_methods:
        record["auth"] = list(host.auth_methods)
    if host.gateways:
        record["gateways"] = list(host.gateways)
    return record


def hosts_document(hosts: list[ExportHost]) -> dict[str, Any]:
    return {
        "schemaVersion": 1,
        "generator": f"xpipe-to-ssh {__version__}",
        "hosts": [_host_record(host) for host in hosts],
    }


def ansible_host_names(hosts: list[ExportHost]) -> list[str]:
    return unique_names([sanitize_alias(host.alias, allow_slash=False) for host in hosts])


def _ansible_variables(host: ExportHost) -> dict[str, Any]:
    fields = host.fields
    variables: dict[str, Any] = {"ansible_host": fields.hostname}
    if fields.username:
        variables["ansible_user"] = fields.username
    if fields.port is not None:
        variables["ansible_port"] = fields.port
    if fields.identity_files:
        variables["ansible_ssh_private_key_file"] = fields.identity_files[0]
    common_args: list[str] = []
    if fields.proxy_command:
        common_args += ["-o", f"ProxyCommand={fields.proxy_command}"]
    for key, value in fields.options:
        common_args += ["-o", f"{key}={value}"]
    if fields.forward_x11:
        common_args += ["-o", "ForwardX11=yes"]
    if common_args:
        # Ansible splits this on whitespace, so a ProxyCommand containing
        # spaces must be quoted as one ssh argument.
        variables["ansible_ssh_common_args"] = shlex.join(common_args)
    return variables


def ansible_document(hosts: list[ExportHost]) -> dict[str, Any]:
    names = ansible_host_names(hosts)
    # Only ``all`` and group keys are allowed at the top level: any other key
    # would be read as an inventory group.
    return {
        "all": {
            "hosts": {
                name: _ansible_variables(host) for name, host in zip(names, hosts, strict=True)
            }
        }
    }


def _dump_yaml(document: dict[str, Any]) -> str:
    body = yaml.safe_dump(
        document,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
    )
    return f"{EXPORT_HEADER}\n{body}"


def render_export(result: ExportResult, fmt: ExportFormat) -> str:
    if fmt == "ssh-config":
        return render_ssh_config(result.hosts)
    if fmt == "yaml":
        return _dump_yaml(hosts_document(result.hosts))
    if fmt == "ansible":
        return _dump_yaml(ansible_document(result.hosts))
    # JSON has no comment syntax, so the generator is a field instead.
    return json.dumps(hosts_document(result.hosts), indent=2) + "\n"


def write_document(text: str, target: Path, *, force: bool) -> None:
    """Write the export atomically, refusing to clobber a file by default.

    The document can name key files and carry a ProxyCommand, so it is written
    ``0600`` and moved into place only once it is complete.
    """
    if target.exists() and not force:
        raise ExportOutputError(f"Refusing to overwrite {target}; pass --force to replace it")
    temporary: str | None = None
    try:
        target.parent.mkdir(parents=True, exist_ok=True)
        handle, temporary = tempfile.mkstemp(
            dir=str(target.parent), prefix=f".{target.name}.", suffix=".tmp"
        )
        with os.fdopen(handle, "w", encoding="utf-8") as stream:
            stream.write(text)
        os.chmod(temporary, 0o600)
        os.replace(temporary, target)
    except OSError as exc:
        raise ExportOutputError(f"Could not write {target}: {exc}") from exc
    finally:
        if temporary is not None and os.path.exists(temporary):
            with contextlib.suppress(OSError):
                os.remove(temporary)
